#!/usr/bin/env bash
# Rebuild assets/fonts.css from the product's own font files.
#
#   scripts/extract-fonts.sh
#
# The product self-hosts Source Sans Pro and declares three faces in
# src/scss/base/_fonts.scss: 300, 400 and bold. This script subsets those same
# three files to the characters a demo page uses, converts them to woff2, and
# writes them into assets/fonts.css as base64 data URIs.
#
# Data URIs keep hard rule 3 intact: the page still makes zero network requests.
# Subsetting is what makes this affordable — a full TTF is 262K, the subset is
# about 13K.
#
# Needs pyftsubset with brotli. If it is missing:
#   python3 -m venv /tmp/fontvenv && /tmp/fontvenv/bin/pip install fonttools brotli
#   PATH=/tmp/fontvenv/bin:$PATH scripts/extract-fonts.sh
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FRONTEND="${BANDA_FRONTEND:-$HOME/work/greenlight-client}"
FONT_DIR="$FRONTEND/src/assets/fonts"
OUT="$SKILL_DIR/assets/fonts.css"

command -v pyftsubset >/dev/null || {
  echo "error: pyftsubset not found. See the header of this script." >&2; exit 1; }
[ -d "$FONT_DIR" ] || { echo "error: no font directory at $FONT_DIR" >&2; exit 1; }

# Latin text plus the punctuation demo copy uses: dashes, curly quotes, bullet,
# ellipsis, middot, euro, arrow.
RANGES='U+0020-007E,U+00A0-00FF,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2022,U+2026,U+00B7,U+20AC,U+2192'
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

{
  echo "/* ====================================================================="
  echo "   Banda demo pages — the product's own type, embedded."
  echo ""
  echo "   Generated by scripts/extract-fonts.sh. Do not hand-edit."
  echo "   Source: $(basename "$FRONTEND")/src/assets/fonts, subset to Latin + demo"
  echo "   punctuation, converted to woff2, inlined as base64 data URIs."
  echo ""
  echo "   These are the three faces src/scss/base/_fonts.scss declares: 300, 400"
  echo "   and bold. The product declares no 600 face, so weight 600 resolves to"
  echo "   bold there. Embedding the same three faces reproduces that, instead of"
  echo "   inventing a semibold the product does not have."
  echo ""
  echo "   local() comes first, as it does in the product: a machine with Source"
  echo "   Sans Pro installed uses its own copy and skips the data URI."
  echo ""
  echo "   Source Sans Pro (c) 2010-2020 Adobe, https://github.com/adobe-fonts"
  echo "   Licensed under the SIL Open Font License 1.1 (OFL-1.1), which permits"
  echo "   embedding in a document like this one."
  echo "   ===================================================================== */"
  echo ""

  for face in "Light:300" "Regular:400" "Bold:bold"; do
    file="${face%%:*}"
    weight="${face##*:}"
    src="$FONT_DIR/SourceSansPro-$file.ttf"
    [ -f "$src" ] || { echo "error: missing $src" >&2; exit 1; }
    pyftsubset "$src" --unicodes="$RANGES" --layout-features='kern,liga' \
      --flavor=woff2 --output-file="$TMP/$file.woff2"
    size_k=$(( $(stat -c%s "$TMP/$file.woff2") / 1024 ))
    echo "/* SourceSansPro-$file.ttf → ${size_k}K subset */"
    echo "@font-face {"
    echo "  font-family: 'Source Sans Pro';"
    echo "  font-style: normal;"
    echo "  font-weight: $weight;"
    echo "  font-display: swap;"
    printf "  src: local('Source Sans Pro'), url(data:font/woff2;base64,"
    base64 -w 0 "$TMP/$file.woff2"
    echo ") format('woff2');"
    echo "}"
    echo ""
  done
} > "$OUT"

echo "wrote: $OUT ($(( $(stat -c%s "$OUT") / 1024 ))K)"
echo "next:  bump 'Assets version:' in assets/tokens.css, then rebuild demos"
